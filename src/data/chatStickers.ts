export const CUTE_ANIMATED_STICKERS = GRAFFITI_STICKERS;

// Helper to check if a message text is a sticker token e.g. [sticker:fire-emoji-animation-gif-download-9861831]
export function parseStickerMessage(text: string): AnimatedSticker | null {
  if (!text) return null;
  const match = text.trim().match(/^\[sticker:([a-zA-Z0-9_-]+)\]$/);
  if (!match) return null;
  const stickerId = match[1];
  return GRAFFITI_STICKERS.find((s) => s.id === stickerId) || null;
}
